    <p>A palavra vem do grego <em>psyché</em> (mente, alma) e <em>logos</em> (estudo). Hoje, a Psicologia é uma ciência que investiga, com método científico, como as pessoas pensam, sentem, aprendem, se comportam e se relacionam, e aplica esse conhecimento para promover a saúde psicológica e a qualidade de vida.</p>

    <h2>O que faz um psicólogo?</h2>
    <p>O psicólogo avalia, compreende e intervém sobre dificuldades emocionais, comportamentais, cognitivas e relacionais. Na prática clínica, isto inclui:</p>
    <ul>
        <li><strong>Avaliação psicológica</strong>: entrevistas, observação e instrumentos padronizados para compreender o funcionamento de cada pessoa;</li>
        <li><strong>Psicoterapia</strong>: acompanhamento regular, com objetivos definidos em conjunto, para lidar com o sofrimento e desenvolver novas competências;</li>
        <li><strong>Psicoeducação</strong>: explicar de forma clara o que está a acontecer, para que a pessoa e a família compreendam e participem no processo;</li>
        <li><strong>Articulação</strong> com familiares, escola e outros profissionais de saúde, quando é necessário e autorizado.</li>
    </ul>

