    <p>Muitas vezes, o melhor cuidado resulta do trabalho em conjunto: psicoterapia com o psicólogo e, quando indicado, acompanhamento médico com o psiquiatra.</p>

    <h2>Áreas da Psicologia</h2>
    <p>A Psicologia tem várias áreas de aplicação: clínica e da saúde, educacional, do trabalho e das organizações, forense, comunitária e a <a href="{{ route('paginas.o-que-e-neuropsicologia') }}">Neuropsicologia</a>, entre outras. Dentro da psicologia clínica existem diferentes abordagens; uma das mais estudadas é a <a href="{{ route('paginas.terapia-cognitivo-comportamental-tcc') }}">Terapia Cognitivo-Comportamental (TCC)</a>.</p>

    <h2>Quando procurar um psicólogo?</h2>
    <p>Não é preciso estar em crise para procurar ajuda. Vale a pena considerar um acompanhamento quando:</p>
    <ul>
        <li>a tristeza, a <a href="{{ route('paginas.ansiedade') }}">ansiedade</a> ou a irritabilidade se mantêm por semanas e afetam o dia a dia;</li>
        <li>há dificuldades de atenção, aprendizagem ou comportamento, em crianças ou adultos;</li>
        <li>os relacionamentos familiares, conjugais ou profissionais se tornam fonte frequente de sofrimento;</li>
        <li>se atravessa uma mudança importante: luto, separação, mudança de país, novo papel na família;</li>
        <li>existe o desejo de se conhecer melhor e de cuidar da saúde psicológica de forma preventiva.</li>
    </ul>

    <h2>A profissão em Portugal e no Brasil</h2>
    <p>Em Portugal, só pode exercer como psicólogo quem está inscrito na <strong>Ordem dos Psicólogos Portugueses (OPP)</strong>, que atribui uma cédula profissional e zela pelo cumprimento do Código Deontológico. No Brasil, o exercício da profissão exige inscrição no <strong>Conselho Regional de Psicologia (CRP)</strong> da região onde o psicólogo atua. Em ambos os países, o sigilo profissional é um dever ético.</p>
