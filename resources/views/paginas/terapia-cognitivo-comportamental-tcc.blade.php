    <p>A Terapia Cognitivo-Comportamental (TCC) foi desenvolvida a partir dos anos 1960, sobretudo pelo psiquiatra norte-americano Aaron T. Beck, integrando contributos da terapia comportamental. Parte de uma ideia simples: a forma como interpretamos as situações influencia o que sentimos e o que fazemos.</p>

    <h2>A relação entre pensamentos, emoções e comportamentos</h2>
    <p>Imagine que um amigo não responde a uma mensagem. Se o pensamento for "está chateado comigo", surge ansiedade e talvez o impulso de evitar o contacto. Se for "deve estar ocupado", a emoção é outra, e o comportamento também. A TCC ajuda a identificar estes <strong>pensamentos automáticos</strong>, a avaliar se correspondem aos factos e a construir alternativas mais equilibradas e úteis.</p>
    <p>A TCC é uma abordagem estruturada e orientada para objetivos, que procura compreender a relação entre pensamentos, emoções e comportamentos. O processo terapêutico é colaborativo e individualizado, respeitando as necessidades e os objetivos de cada pessoa.</p>

    <h2>Como funciona uma sessão de TCC?</h2>
    <ol>
        <li><strong>Avaliação e definição de objetivos</strong>: nas primeiras sessões, compreende-se a história, as dificuldades atuais e o que a pessoa quer mudar.</li>
        <li><strong>Formulação do caso</strong>: terapeuta e paciente constroem juntos uma explicação de como o problema se mantém.</li>
        <li><strong>Intervenção</strong>: as sessões têm uma estrutura clara, com temas combinados e exercícios práticos.</li>
        <li><strong>Prática entre sessões</strong>: pequenas tarefas ajudam a levar o que se trabalhou para o quotidiano.</li>
        <li><strong>Prevenção de recaídas</strong>: no final, consolida-se o que funcionou para a pessoa continuar a usar sozinha.</li>
    </ol>

    <h2>Técnicas mais usadas</h2>
    <ul>
        <li><strong>Psicoeducação</strong>: compreender o que se passa, por exemplo, como funciona o ciclo da ansiedade;</li>
        <li><strong>Reestruturação cognitiva</strong>: identificar e questionar pensamentos distorcidos;</li>
        <li><strong>Exposição gradual</strong>: enfrentar, de forma planeada e segura, situações evitadas por medo;</li>
        <li><strong>Ativação comportamental</strong>: retomar atividades com significado, muito usada na depressão;</li>
        <li><strong>Treino de resolução de problemas</strong> e de competências sociais e emocionais;</li>
        <li><strong>Técnicas de regulação emocional</strong>, como respiração e relaxamento.</li>
    </ul>

    <h2>Para que dificuldades a TCC é indicada?</h2>
    <p>A TCC é uma das abordagens psicológicas com maior volume de investigação científica, com evidências de eficácia em diferentes dificuldades, entre elas:</p>
    <ul>
        <li><a href="{{ route('paginas.ansiedade') }}">perturbações de ansiedade</a>, pânico e fobias;</li>
        <li><a href="{{ route('paginas.depressao') }}">depressão</a>;</li>
        <li>perturbação obsessivo-compulsiva;</li>
        <li>insónia, stress e dificuldades de regulação emocional;</li>
        <li>dificuldades associadas à <a href="{{ route('paginas.tdah-phda') }}">PHDA</a> em adultos, como organização e gestão do tempo;</li>
        <li>dificuldades nos relacionamentos.</li>
    </ul>
    <p>Mais do que compreender as dificuldades, a TCC procura promover mudanças concretas, fortalecer competências emocionais e contribuir para uma melhor qualidade de vida.</p>

    <h2>Quanto tempo dura?</h2>
    <p>Depende da pessoa e dos objetivos. Muitos acompanhamentos em TCC são de duração limitada, com sessões semanais de cerca de 50 minutos e avaliação regular do progresso. A duração é sempre combinada e revista em conjunto.</p>
