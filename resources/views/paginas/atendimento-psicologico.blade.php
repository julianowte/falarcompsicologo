    <h2>Abordagem psicológica: Terapia Cognitivo-Comportamental (TCC)</h2>
    <p>A minha principal abordagem de intervenção é a <a href="{{ route('paginas.terapia-cognitivo-comportamental-tcc') }}">Terapia Cognitivo-Comportamental (TCC)</a>, uma das abordagens psicológicas com maior volume de investigação científica e evidências de eficácia para diferentes dificuldades emocionais e comportamentais.</p>
    <p>A TCC é uma abordagem estruturada e orientada para objetivos, que procura compreender a relação entre pensamentos, emoções e comportamentos.</p>
    <p>Ao longo do acompanhamento, trabalhamos na identificação de padrões de pensamento e comportamento que podem contribuir para o sofrimento psicológico, desenvolvendo estratégias mais adaptativas para lidar com as situações do quotidiano.</p>
    <p>O processo terapêutico é colaborativo e individualizado, respeitando as necessidades e os objetivos de cada pessoa.</p>
    <p>Mais do que compreender as dificuldades, a TCC procura promover mudanças concretas, fortalecer competências emocionais e contribuir para uma melhor qualidade de vida.</p>

    <h2>Intervenção nas perturbações do neurodesenvolvimento</h2>
    <p>Uma das minhas áreas de atuação é a intervenção psicológica junto de pessoas com perturbações do neurodesenvolvimento, especialmente através da intervenção precoce e de estratégias fundamentadas na <a href="{{ route('paginas.o-que-e-aba') }}">Análise do Comportamento Aplicada (ABA)</a>.</p>
    <p>Esta intervenção destina-se, entre outros públicos, a <a href="{{ route('paginas.o-que-e-autismo-segundo-o-dsm') }}">pessoas autistas</a> e pessoas com <a href="{{ route('paginas.tdah-phda') }}">Perturbação de Hiperatividade e Défice de Atenção (PHDA)</a>.</p>
    <p>O objetivo é promover o desenvolvimento de competências que favoreçam a autonomia, a comunicação, a aprendizagem, a interação social e a adaptação aos diferentes contextos da vida.</p>
    <p>O trabalho é individualizado e considera as características, necessidades, potencialidades e o contexto de cada pessoa. Entre as competências que podem ser trabalhadas, destacam-se:</p>
    <ul>
        <li>Comunicação e interação social;</li>
        <li>Autorregulação emocional;</li>
        <li>Atenção e concentração;</li>
        <li>Organização e planeamento;</li>
        <li>Desenvolvimento de competências adaptativas;</li>
        <li>Autonomia nas atividades do quotidiano;</li>
        <li>Resolução de problemas.</li>
    </ul>
    <p>As estratégias são definidas de acordo com as necessidades individuais, respeitando o ritmo, a dignidade e a singularidade de cada pessoa.</p>

    <h2>Neuropsicologia e avaliação neuropsicológica</h2>
    <p>Através da <a href="{{ route('paginas.o-que-e-neuropsicologia') }}">avaliação neuropsicológica</a>, é possível investigar funções como a atenção, a memória, a linguagem, o raciocínio e as funções executivas, compreendendo o perfil cognitivo e funcional de cada pessoa. Este processo pode contribuir para o esclarecimento de hipóteses diagnósticas e para a orientação de intervenções individualizadas.</p>

