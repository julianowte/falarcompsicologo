    <p>Todos passamos por dias tristes. A depressão é diferente: é uma condição de saúde que afeta o humor, os pensamentos, o corpo e o comportamento, de forma persistente, e interfere na capacidade de viver o dia a dia. A Organização Mundial da Saúde considera-a uma das principais causas de incapacidade em todo o mundo. E, sobretudo, a depressão tem tratamento.</p>

    <h2>Tristeza ou depressão?</h2>
    <p>A tristeza é uma emoção natural, normalmente ligada a um acontecimento, e vai passando com o tempo. Na depressão, o humor em baixo ou a perda de interesse mantêm-se durante semanas, quase todos os dias, e vêm acompanhados de outras alterações que dificultam trabalhar, estudar, cuidar de si e relacionar-se.</p>

    <h2>Sinais e sintomas</h2>
    <p>Segundo o <a href="{{ route('paginas.o-que-e-o-dsm') }}">DSM-5-TR</a>, a perturbação depressiva major envolve pelo menos <strong>cinco</strong> dos sintomas seguintes, durante pelo menos <strong>duas semanas</strong>, sendo obrigatoriamente um dos dois primeiros:</p>
    <ol>
        <li>humor deprimido na maior parte do dia (nas crianças e adolescentes, pode surgir como irritabilidade);</li>
        <li>perda marcada de interesse ou prazer nas atividades;</li>
        <li>alterações do apetite ou do peso;</li>
        <li>insónia ou dormir em excesso;</li>
        <li>agitação ou lentificação dos movimentos;</li>
        <li>cansaço ou falta de energia;</li>
        <li>sentimentos de inutilidade ou culpa excessiva;</li>
        <li>dificuldade de concentração ou em tomar decisões;</li>
        <li>pensamentos recorrentes sobre a morte ou ideação suicida.</li>
    </ol>
    <p>Só um profissional de saúde pode fazer o diagnóstico, mas reconhecer estes sinais é um primeiro passo importante para pedir ajuda.</p>

    <div class="destaque">
        <p><strong>Se tem pensamentos de morte ou de se magoar, não espere.</strong> Em Portugal, ligue SNS 24 (808 24 24 24) ou 112. No Brasil, ligue 188 (CVV, 24 horas, gratuito) ou 192 (SAMU). Fale com alguém de confiança e procure o serviço de urgência mais próximo.</p>
    </div>

    <h2>O que pode contribuir para a depressão?</h2>
    <p>Não existe uma causa única. A depressão resulta da combinação de fatores biológicos, psicológicos e sociais: predisposição familiar, acontecimentos de vida difíceis (perdas, separações, desemprego, mudança de país), stress prolongado, isolamento, doenças físicas e padrões de pensamento muito autocríticos. Não é fraqueza nem falta de força de vontade.</p>

    <h2>Tratamento</h2>
    <p>A depressão é tratável, e o tratamento é ajustado à intensidade dos sintomas:</p>
    <ul>
        <li><strong>Psicoterapia</strong>: a <a href="{{ route('paginas.terapia-cognitivo-comportamental-tcc') }}">Terapia Cognitivo-Comportamental (TCC)</a> tem forte evidência científica. Trabalha a ativação comportamental (retomar atividades com significado), a identificação de pensamentos negativos automáticos e a resolução de problemas;</li>
        <li><strong>Acompanhamento médico</strong>: em quadros moderados a graves, o médico pode recomendar medicação antidepressiva, muitas vezes em conjunto com a psicoterapia;</li>
        <li><strong>Cuidados no dia a dia</strong>: sono regular, atividade física, alimentação e manter o contacto com pessoas de confiança ajudam na recuperação.</li>
    </ul>

    <h2>Depressão e ansiedade</h2>
    <p>É comum que a depressão surja acompanhada de <a href="{{ route('paginas.ansiedade') }}">ansiedade</a>. Também pode estar associada a outras condições, como a <a href="{{ route('paginas.tdah-phda') }}">PHDA</a>. Uma boa avaliação ajuda a compreender o quadro completo e a definir o acompanhamento mais adequado.</p>
