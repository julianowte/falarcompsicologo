    <p>A Neuropsicologia é a área que estuda a relação entre o funcionamento cerebral e os processos cognitivos, emocionais e comportamentais. O neuropsicólogo é um psicólogo com formação especializada nesta área, que avalia e intervém sobre funções como a atenção, a memória, a linguagem e as funções executivas.</p>

    <h2>O que é a avaliação neuropsicológica?</h2>
    <p>Através da avaliação neuropsicológica, é possível investigar diferentes funções cognitivas, como:</p>
    <ul>
        <li>Atenção e concentração;</li>
        <li>Memória e aprendizagem;</li>
        <li>Linguagem e comunicação;</li>
        <li>Raciocínio e funções intelectuais;</li>
        <li>Funções executivas, como planeamento, organização e tomada de decisões;</li>
        <li>Regulação emocional e comportamento.</li>
    </ul>
    <p>A avaliação permite compreender o perfil cognitivo e funcional de cada pessoa, identificando potencialidades, dificuldades e possíveis alterações que possam interferir nas atividades do quotidiano.</p>

    <h2>Quando é indicada?</h2>
    <p>A avaliação neuropsicológica pode ser útil, em crianças, adolescentes e adultos, quando há:</p>
    <ul>
        <li>suspeita de <a href="{{ route('paginas.tdah-phda') }}">PHDA (TDAH)</a> ou de <a href="{{ route('paginas.o-que-e-autismo-segundo-o-dsm') }}">autismo</a>;</li>
        <li>dificuldades de aprendizagem, como dislexia ou discalculia;</li>
        <li>queixas de memória, atenção ou concentração;</li>
        <li>necessidade de compreender o impacto de uma condição neurológica, como um traumatismo craniano ou um AVC;</li>
        <li>necessidade de orientar a intervenção terapêutica, escolar ou profissional.</li>
    </ul>

    <h2>Como decorre o processo?</h2>
    <ol>
        <li><strong>Entrevista inicial</strong>: recolha da história clínica, do desenvolvimento e das queixas atuais, com a pessoa e, quando adequado, com a família;</li>
        <li><strong>Aplicação de testes</strong>: instrumentos padronizados e validados, aplicados em uma ou mais sessões, adaptados à idade e às características da pessoa;</li>
        <li><strong>Análise e integração</strong>: os resultados são interpretados em conjunto com a história e a observação clínica;</li>
        <li><strong>Relatório e devolução</strong>: os resultados são explicados de forma clara, com recomendações práticas para a pessoa, a família, a escola ou outros profissionais.</li>
    </ol>

    <h2>Para que serve o resultado?</h2>
    <p>Este processo pode contribuir para o esclarecimento de hipóteses diagnósticas, a identificação de necessidades específicas, a orientação de intervenções e a elaboração de estratégias individualizadas.</p>
    <p>O objetivo é proporcionar uma compreensão mais ampla do funcionamento de cada pessoa, contribuindo para decisões clínicas mais fundamentadas e para a promoção da autonomia e da qualidade de vida.</p>
