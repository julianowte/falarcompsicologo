    <h2>Neurodiversidade e neurodivergência</h2>
    <p><strong>Neurodiversidade</strong> é a ideia de que os cérebros humanos funcionam de formas naturalmente diferentes, tal como existe diversidade em tantas outras características humanas. O termo ganhou força no final dos anos 1990, associado à socióloga australiana Judy Singer e ao movimento de pessoas autistas.</p>
    <p><strong>Neurodivergente</strong> é a pessoa cujo funcionamento neurológico se afasta do que é considerado típico. Quem tem um funcionamento considerado típico é, por vezes, descrito como <strong>neurotípico</strong>.</p>
    <p>Neurodivergência <strong>não é um diagnóstico</strong> nem consta do <a href="{{ route('paginas.o-que-e-o-dsm') }}">DSM</a>. É um conceito usado para falar destas diferenças com mais respeito e menos estigma.</p>

    <h2>Quem pode ser neurodivergente?</h2>
    <p>O termo é usado, entre outras, para pessoas com:</p>
    <ul>
        <li><a href="{{ route('paginas.o-que-e-autismo-segundo-o-dsm') }}">autismo</a>;</li>
        <li><a href="{{ route('paginas.tdah-phda') }}">PHDA (TDAH)</a>;</li>
        <li>dislexia, discalculia e disgrafia;</li>
        <li>perturbação do desenvolvimento da coordenação (dispraxia);</li>
        <li>síndrome de Tourette e outras perturbações de tiques;</li>
        <li>altas capacidades, em algumas abordagens.</li>
    </ul>

    <h2>Diferença não é sinónimo de défice</h2>
    <p>A perspetiva da neurodiversidade lembra que muitas dificuldades sentidas por pessoas neurodivergentes resultam do encontro entre o seu funcionamento e um ambiente pensado para outro tipo de funcionamento, como salas barulhentas, regras sociais implícitas ou ritmos rígidos. Ao mesmo tempo, não nega que existem desafios reais, que podem causar sofrimento e exigir apoio especializado.</p>

    <h2>O que é uma prática neuroafirmativa?</h2>
    <p>Uma intervenção neuroafirmativa procura:</p>
    <ul>
        <li>valorizar as potencialidades e os interesses da pessoa;</li>
        <li>respeitar a sua forma de comunicar, sentir e processar a informação;</li>
        <li>definir objetivos que aumentem a autonomia, o bem-estar e a qualidade de vida, e não apenas "parecer típico";</li>
        <li>adaptar os ambientes, e não só a pessoa;</li>
        <li>envolver a pessoa e a família nas decisões.</li>
    </ul>
    <p>É com este olhar que trabalho na intervenção com pessoas neurodivergentes, incluindo as estratégias fundamentadas na <a href="{{ route('paginas.o-que-e-aba') }}">ABA</a>, respeitando o ritmo, a dignidade e a singularidade de cada pessoa.</p>

    <h2>Neurodivergência e saúde psicológica</h2>
    <p>Pessoas neurodivergentes têm maior probabilidade de viver <a href="{{ route('paginas.ansiedade') }}">ansiedade</a>, <a href="{{ route('paginas.depressao') }}">depressão</a> e exaustão, muitas vezes ligadas ao esforço constante de adaptação. Compreender o próprio funcionamento, através de uma <a href="{{ route('paginas.o-que-e-neuropsicologia') }}">avaliação neuropsicológica</a> e de acompanhamento psicológico, pode trazer alívio, autoconhecimento e estratégias mais ajustadas.</p>
