    <p>ABA é a sigla inglesa de <em>Applied Behavior Analysis</em>, ou Análise do Comportamento Aplicada. É uma área da ciência do comportamento que estuda como os comportamentos são aprendidos e mantidos, e usa esse conhecimento para ensinar competências importantes para a vida de cada pessoa.</p>

    <h2>Em que se baseia a ABA?</h2>
    <p>A ABA assenta em princípios da aprendizagem estudados há décadas: o comportamento é influenciado pelo que acontece antes (o contexto) e pelo que acontece depois (as consequências). Quando uma ação é seguida de algo significativo para a pessoa, tende a repetir-se; a isto chama-se <strong>reforço</strong>.</p>
    <p>Na prática, a intervenção:</p>
    <ul>
        <li>começa por uma <strong>avaliação</strong> das competências, interesses e necessidades da pessoa;</li>
        <li>define <strong>objetivos individualizados</strong>, relevantes para o dia a dia e combinados com a família;</li>
        <li>divide competências complexas em <strong>pequenos passos</strong>, ensinados de forma gradual;</li>
        <li>usa o <strong>reforço positivo</strong> e os interesses da pessoa para motivar a aprendizagem;</li>
        <li><strong>regista dados</strong> de forma sistemática, para ajustar a intervenção ao progresso real;</li>
        <li>procura a <strong>generalização</strong>: que a competência aprendida seja usada em casa, na escola e na comunidade.</li>
    </ul>

    <h2>Para quem é indicada?</h2>
    <p>A ABA é mais conhecida pela intervenção com <a href="{{ route('paginas.o-que-e-autismo-segundo-o-dsm') }}">pessoas autistas</a>, sobretudo na intervenção precoce, mas os seus princípios são também usados com pessoas com <a href="{{ route('paginas.tdah-phda') }}">PHDA (TDAH)</a>, outras perturbações do neurodesenvolvimento e em contextos educativos.</p>

    <h2>Que competências podem ser trabalhadas?</h2>
    <ul>
        <li>Comunicação e interação social;</li>
        <li>Autorregulação emocional;</li>
        <li>Atenção e concentração;</li>
        <li>Organização e planeamento;</li>
        <li>Competências adaptativas e autonomia nas atividades do quotidiano (vestir, alimentação, higiene);</li>
        <li>Resolução de problemas e aprendizagem escolar.</li>
    </ul>

    <h2>Uma intervenção com respeito pela pessoa</h2>
    <p>A forma de aplicar a ABA evoluiu muito. Hoje, uma intervenção ética procura desenvolver competências que <strong>aumentem a autonomia e a qualidade de vida</strong> da pessoa, e não tornar o seu comportamento "igual ao dos outros". Isto significa respeitar o ritmo, os interesses, a forma de comunicar e a dignidade de cada pessoa, ouvir a família e, sempre que possível, a própria pessoa, e evitar práticas que causem sofrimento.</p>
    <p>No meu trabalho, as estratégias fundamentadas na ABA são definidas de acordo com as necessidades individuais, respeitando o ritmo, a dignidade e a singularidade de cada pessoa. Saiba mais sobre a <a href="{{ route('paginas.neurodivergencia') }}">neurodivergência</a> e sobre o <a href="{{ route('paginas.atendimento-psicologico') }}">meu atendimento</a>.</p>

    <h2>Onde acontece a intervenção?</h2>
    <p>A intervenção pode decorrer em consultório, ao domicílio ou em contexto escolar. Trabalhar nos ambientes do quotidiano ajuda a que as competências se transfiram para a vida real e permite a articulação com familiares, cuidadores e professores, quando pertinente e autorizado.</p>
