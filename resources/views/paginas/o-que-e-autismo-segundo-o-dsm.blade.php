    <h2>Especificadores</h2>
    <p>O diagnóstico é complementado com informação que ajuda a planear o apoio, indicando se existe ou não:</p>
    <ul>
        <li>défice intelectual associado;</li>
        <li>alteração da linguagem associada;</li>
        <li>associação a uma condição genética ou médica conhecida, ou a um fator ambiental;</li>
        <li>associação a outra perturbação do neurodesenvolvimento, mental ou comportamental, por exemplo, <a href="{{ route('paginas.tdah-phda') }}">PHDA</a> ou <a href="{{ route('paginas.ansiedade') }}">ansiedade</a>;</li>
        <li>catatonia.</li>
    </ul>

    <h2>Como é feito o diagnóstico?</h2>
    <p>Não existe um exame de sangue ou de imagem que diagnostique o autismo. O diagnóstico é clínico e deve ser feito por profissionais com experiência, muitas vezes em equipa multidisciplinar (pediatria do desenvolvimento, pedopsiquiatria ou psiquiatria, psicologia, terapia da fala, entre outros). Inclui a história do desenvolvimento, a observação direta e, frequentemente, instrumentos padronizados e uma <a href="{{ route('paginas.o-que-e-neuropsicologia') }}">avaliação neuropsicológica</a> do perfil cognitivo.</p>
    <p>O diagnóstico pode acontecer em qualquer idade. Muitos adultos, sobretudo mulheres, só recebem o diagnóstico mais tarde, porque aprenderam a camuflar as suas características.</p>

    <h2>E depois do diagnóstico?</h2>
    <p>O autismo não é uma doença a "curar", mas uma forma diferente de funcionamento neurológico. O objetivo do apoio é promover a comunicação, a autonomia, a regulação emocional e a participação nos contextos de vida, respeitando a identidade da pessoa. A <a href="{{ route('paginas.o-que-e-aba') }}">intervenção baseada em ABA</a>, a terapia da fala, a terapia ocupacional e o apoio à família e à escola são algumas das respostas possíveis. Saiba mais sobre <a href="{{ route('paginas.neurodivergencia') }}">neurodivergência</a>.</p>
