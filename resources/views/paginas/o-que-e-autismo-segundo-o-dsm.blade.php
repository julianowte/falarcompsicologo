    <p>O <a href="{{ route('paginas.o-que-e-o-dsm') }}">DSM</a> é o manual de diagnóstico publicado pela Associação Americana de Psiquiatria. Na sua edição atual, o <strong>DSM-5-TR</strong> (2022), o autismo é designado <strong>Perturbação do Espetro do Autismo</strong> em Portugal e <strong>Transtorno do Espectro Autista (TEA)</strong> no Brasil. A palavra "espetro" (ou "espectro") traduz a enorme diversidade de características, necessidades e potencialidades entre as pessoas autistas.</p>

    <h2>O que mudou com o DSM-5</h2>
    <p>Até ao DSM-IV existiam diagnósticos separados, como perturbação autística, síndrome de Asperger e perturbação global do desenvolvimento sem outra especificação. Desde o DSM-5 (2013), todos foram reunidos num único diagnóstico, a Perturbação do Espetro do Autismo, acompanhado de níveis de suporte e especificadores que descrevem melhor cada pessoa.</p>

    <h2>Critérios de diagnóstico</h2>
    <p>De forma simplificada, o DSM-5-TR descreve dois grandes domínios.</p>

    <h3>A. Diferenças persistentes na comunicação e na interação social</h3>
    <p>Presentes em vários contextos e manifestadas nas <strong>três</strong> áreas seguintes:</p>
    <ol>
        <li>reciprocidade socioemocional, por exemplo, na partilha de interesses e emoções ou no vai e vem de uma conversa;</li>
        <li>comportamentos comunicativos não verbais, como o contacto visual, os gestos e a expressão facial;</li>
        <li>desenvolver, manter e compreender relações, incluindo ajustar o comportamento a diferentes contextos sociais.</li>
    </ol>

    <h3>B. Padrões restritos e repetitivos de comportamentos, interesses ou atividades</h3>
    <p>Manifestados em pelo menos <strong>duas</strong> das quatro áreas:</p>
    <ol>
        <li>movimentos, uso de objetos ou fala estereotipados ou repetitivos (por exemplo, alinhar objetos, ecolalia);</li>
        <li>insistência na rotina e dificuldade com mudanças;</li>
        <li>interesses muito intensos ou focados;</li>
        <li>hiper ou hiporreatividade sensorial, por exemplo, a sons, texturas, luzes ou dor.</li>
    </ol>

    <h3>Outros critérios</h3>
    <ul>
        <li><strong>C.</strong> As características estão presentes desde o início do desenvolvimento, embora possam só se tornar evidentes quando as exigências sociais ultrapassam as capacidades, ou ficar mascaradas por estratégias aprendidas;</li>
        <li><strong>D.</strong> Causam impacto significativo no funcionamento social, escolar, profissional ou noutras áreas importantes;</li>
        <li><strong>E.</strong> Não são melhor explicadas por perturbação do desenvolvimento intelectual ou por atraso global do desenvolvimento.</li>
    </ul>

    <h2>Níveis de suporte</h2>
    <p>O DSM-5-TR indica a intensidade de apoio necessária, separadamente para cada um dos dois domínios. O nível pode variar ao longo da vida e entre contextos.</p>
