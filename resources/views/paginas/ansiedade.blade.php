    <h2>Sinais e sintomas mais comuns</h2>
    <ul>
        <li><strong>No corpo</strong>: coração acelerado, aperto no peito, falta de ar, tensão muscular, tremores, suores, tonturas, problemas digestivos, cansaço;</li>
        <li><strong>Nos pensamentos</strong>: preocupação constante, antecipação do pior, dificuldade em "desligar", dificuldade de concentração;</li>
        <li><strong>Nas emoções</strong>: nervosismo, irritabilidade, sensação de perigo iminente;</li>
        <li><strong>No comportamento</strong>: evitar situações, procurar constantemente confirmação, alterações do sono.</li>
    </ul>

    <h2>Tipos de perturbações de ansiedade</h2>
    <p>O <a href="{{ route('paginas.o-que-e-o-dsm') }}">DSM-5-TR</a> descreve várias perturbações de ansiedade. As mais frequentes são:</p>
    <ul>
        <li><strong>Perturbação de ansiedade generalizada</strong>: preocupação excessiva e difícil de controlar sobre várias áreas da vida, na maioria dos dias, durante pelo menos seis meses;</li>
        <li><strong>Perturbação de pânico</strong>: ataques de pânico inesperados e recorrentes, com medo intenso de que voltem a acontecer;</li>
        <li><strong>Perturbação de ansiedade social</strong>: medo marcado de ser avaliado negativamente em situações sociais;</li>
        <li><strong>Fobias específicas</strong>: medo intenso de um objeto ou situação concreta, como voar, alturas ou animais;</li>
        <li><strong>Agorafobia</strong>: medo de lugares ou situações de onde seria difícil sair ou pedir ajuda;</li>
        <li><strong>Perturbação de ansiedade de separação</strong>: ansiedade excessiva com a separação de figuras de vinculação, em crianças e também em adultos.</li>
    </ul>

    <h2>Como a psicoterapia ajuda</h2>
    <p>As perturbações de ansiedade têm tratamento. A <a href="{{ route('paginas.terapia-cognitivo-comportamental-tcc') }}">Terapia Cognitivo-Comportamental (TCC)</a> é uma das abordagens com mais evidência científica nesta área. No acompanhamento trabalha-se, por exemplo:</p>
    <ul>
        <li>compreender o ciclo da ansiedade e por que razão evitar alivia no momento, mas mantém o problema;</li>
        <li>identificar e questionar pensamentos catastróficos;</li>
        <li>enfrentar, de forma gradual e segura, as situações evitadas;</li>
        <li>aprender técnicas de regulação, como a respiração e o relaxamento;</li>
        <li>reduzir comportamentos de verificação e procura de confirmação.</li>
    </ul>
    <p>Em alguns casos, pode ser útil o acompanhamento médico em paralelo, para avaliar a necessidade de medicação.</p>

    <h2>Quando procurar ajuda?</h2>
    <p>Quando a ansiedade se mantém por semanas, causa sofrimento ou leva a deixar de fazer coisas importantes. Ansiedade e <a href="{{ route('paginas.depressao') }}">depressão</a> aparecem muitas vezes juntas, e a ansiedade também é frequente em pessoas com <a href="{{ route('paginas.tdah-phda') }}">PHDA</a> ou <a href="{{ route('paginas.o-que-e-autismo-segundo-o-dsm') }}">autismo</a>. Uma avaliação ajuda a perceber o que está a acontecer e qual o melhor caminho.</p>
