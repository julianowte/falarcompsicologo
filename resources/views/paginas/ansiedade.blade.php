    <p>A ansiedade é uma resposta natural do organismo perante situações percebidas como ameaçadoras ou incertas. Em doses adequadas, prepara-nos para agir: ajuda a estudar para um exame ou a ter cuidado ao atravessar a rua. O problema surge quando é desproporcionada, persistente e começa a limitar a vida.</p>

