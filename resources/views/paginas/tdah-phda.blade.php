    <p>Em Portugal, usa-se a sigla <strong>PHDA</strong> (Perturbação de Hiperatividade e Défice de Atenção). No Brasil, <strong>TDAH</strong> (Transtorno do Déficit de Atenção com Hiperatividade). Em inglês, ADHD. Todas descrevem a mesma condição do neurodesenvolvimento.</p>

    <h2>O que é a PHDA (TDAH)?</h2>
    <p>Segundo o <a href="{{ route('paginas.o-que-e-o-dsm') }}">DSM-5-TR</a>, a PHDA caracteriza-se por um padrão persistente de <strong>desatenção</strong> e/ou <strong>hiperatividade-impulsividade</strong>, mais intenso do que o esperado para a idade, que interfere no funcionamento ou no desenvolvimento. Não é preguiça, falta de educação nem falta de força de vontade.</p>

    <h2>Sintomas de desatenção</h2>
    <ul>
        <li>dificuldade em manter a atenção em tarefas ou conversas;</li>
        <li>erros por descuido e dificuldade em prestar atenção a detalhes;</li>
        <li>parecer não ouvir quando lhe falam diretamente;</li>
        <li>não terminar tarefas e dificuldade em seguir instruções;</li>
        <li>dificuldade em organizar tarefas, materiais e tempo;</li>
        <li>evitar tarefas que exigem esforço mental prolongado;</li>
        <li>perder objetos com frequência;</li>
        <li>distrair-se facilmente com estímulos externos ou pensamentos;</li>
        <li>esquecimentos frequentes nas atividades do dia a dia.</li>
    </ul>

    <h2>Sintomas de hiperatividade e impulsividade</h2>
    <ul>
        <li>mexer constantemente as mãos ou os pés, ou remexer-se na cadeira;</li>
        <li>levantar-se em situações em que se espera que permaneça sentado;</li>
        <li>correr ou trepar em situações inadequadas (nos adultos, sensação interna de inquietação);</li>
        <li>dificuldade em brincar ou fazer atividades de lazer em silêncio;</li>
        <li>estar sempre "a mil", como se fosse movido por um motor;</li>
        <li>falar em excesso;</li>
        <li>responder antes de a pergunta terminar;</li>
        <li>dificuldade em esperar pela sua vez;</li>
        <li>interromper ou intrometer-se nas conversas ou atividades dos outros.</li>
    </ul>

    <h2>Critérios de diagnóstico</h2>
    <ul>
        <li><strong>seis ou mais sintomas</strong> numa das dimensões (ou em ambas), durante pelo menos <strong>seis meses</strong>; a partir dos 17 anos, bastam cinco;</li>
        <li>vários sintomas estavam presentes <strong>antes dos 12 anos</strong>;</li>
        <li>os sintomas manifestam-se em <strong>dois ou mais contextos</strong>, como casa, escola, trabalho ou relações sociais;</li>
        <li>há evidência clara de que <strong>interferem</strong> no funcionamento;</li>
        <li>não são melhor explicados por outra condição, como <a href="{{ route('paginas.ansiedade') }}">ansiedade</a> ou <a href="{{ route('paginas.depressao') }}">depressão</a>.</li>
    </ul>
    <p>O DSM-5-TR descreve três apresentações: <strong>predominantemente desatenta</strong>, <strong>predominantemente hiperativa/impulsiva</strong> e <strong>combinada</strong>.</p>

    <h2>PHDA em adultos</h2>
    <p>A PHDA não desaparece necessariamente com a idade. Nos adultos, a hiperatividade visível tende a dar lugar a inquietação interna, e ganham peso as dificuldades de organização, gestão do tempo, procrastinação, esquecimentos e impulsividade nas decisões. Muitos adultos só procuram avaliação quando um filho é diagnosticado, ou depois de anos a sentir que "se esforçam mais do que os outros".</p>

    <h2>Como é feita a avaliação?</h2>
    <p>O diagnóstico é clínico. Inclui entrevista detalhada, história do desenvolvimento, informação de vários contextos (família, escola, trabalho) e questionários padronizados. A <a href="{{ route('paginas.o-que-e-neuropsicologia') }}">avaliação neuropsicológica</a> ajuda a compreender o perfil de atenção e funções executivas e a distinguir a PHDA de outras causas de dificuldades de concentração. A PHDA surge muitas vezes associada a outras condições, como o <a href="{{ route('paginas.o-que-e-autismo-segundo-o-dsm') }}">autismo</a>, perturbações de aprendizagem ou ansiedade.</p>

    <h2>Como é o acompanhamento?</h2>
    <p>O acompanhamento é individualizado e pode combinar:</p>
    <ul>
        <li><strong>psicoeducação</strong> da pessoa e da família sobre o funcionamento da PHDA;</li>
        <li><strong>intervenção psicológica</strong>: estratégias comportamentais, treino de organização e planeamento, regulação emocional e, nos adultos, <a href="{{ route('paginas.terapia-cognitivo-comportamental-tcc') }}">TCC</a>;</li>
        <li><strong>orientação parental</strong> e articulação com a escola;</li>
        <li><strong>acompanhamento médico</strong>, quando indicado, para avaliar a necessidade de medicação, que só pode ser prescrita por médico.</li>
    </ul>
