    <p>DSM é a sigla de <em>Diagnostic and Statistical Manual of Mental Disorders</em>, em português <strong>Manual Diagnóstico e Estatístico de Perturbações Mentais</strong> (no Brasil, "Transtornos Mentais"). Publicado pela American Psychiatric Association (APA), descreve as perturbações mentais e os critérios usados para as diagnosticar.</p>

    <h2>Para que serve o DSM?</h2>
    <ul>
        <li><strong>Linguagem comum</strong>: permite que psicólogos, psiquiatras e outros profissionais usem os mesmos critérios e termos;</li>
        <li><strong>Diagnóstico</strong>: descreve sintomas, duração e impacto necessários para cada diagnóstico;</li>
        <li><strong>Investigação</strong>: critérios uniformes permitem comparar estudos científicos;</li>
        <li><strong>Acesso a apoios</strong>: em muitos contextos, um diagnóstico formal é necessário para aceder a apoios escolares, sociais ou de saúde.</li>
    </ul>

