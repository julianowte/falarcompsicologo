    <h2>Como está organizado?</h2>
    <p>O DSM-5-TR organiza as perturbações em grandes capítulos, como perturbações do neurodesenvolvimento (onde se incluem o <a href="{{ route('paginas.o-que-e-autismo-segundo-o-dsm') }}">autismo</a> e a <a href="{{ route('paginas.tdah-phda') }}">PHDA</a>), perturbações depressivas (<a href="{{ route('paginas.depressao') }}">depressão</a>), perturbações de <a href="{{ route('paginas.ansiedade') }}">ansiedade</a>, perturbação obsessivo-compulsiva e relacionadas, perturbações relacionadas com trauma, entre outras. Para cada uma, descreve critérios de diagnóstico, características, desenvolvimento ao longo da vida e diagnóstico diferencial.</p>

    <h2>DSM e CID: qual a diferença?</h2>
    <p>A <strong>CID</strong> (Classificação Internacional de Doenças) é publicada pela Organização Mundial da Saúde e abrange todas as condições de saúde, não apenas as mentais. A versão atual, a <strong>CID-11</strong>, entrou em vigor em 2022. Em Portugal e no Brasil, a CID é a referência oficial dos sistemas de saúde, enquanto o DSM é amplamente usado na prática clínica e na investigação. As duas classificações são, em grande parte, compatíveis.</p>

    <h2>Os limites de um manual</h2>
    <p>Um diagnóstico é uma ferramenta útil para compreender e orientar a intervenção, mas não define uma pessoa. O DSM descreve categorias; a avaliação clínica considera a história, o contexto, as potencialidades e as necessidades de cada um. Por isso, o diagnóstico deve ser sempre feito por profissionais qualificados, e nunca a partir de listas de sintomas encontradas na internet.</p>
